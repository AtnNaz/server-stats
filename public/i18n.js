  const lang = DICT[document.documentElement.lang] ? document.documentElement.lang : 'tr';
  const locale = lang === 'tr' ? 'tr-TR' : 'en-US';

  function t(key, vars = {}) {
    const template = DICT[lang][key] ?? DICT.tr[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? '' : String(vars[name])));
  }

  function apply(root = document) {
    for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const attr of ['title', 'aria-label', 'placeholder']) {
      for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)));
    }
  }

  window.I18N = { lang, locale, t, apply, DICT };
